"""Verify source cache work generated from the continuous memory model."""
from pathlib import Path
import argparse,hashlib,json,sys
from verify_memory_lifetimes import shape_calls
from sound_memory_calls import sound_calls

ROOT=Path(__file__).resolve().parents[2]


def verify(memory_path,scene_path,cache_path,output):
    output.mkdir(parents=True,exist_ok=False)
    memory=json.loads(memory_path.read_text());scene=json.loads(scene_path.read_text());cache=json.loads(cache_path.read_text())
    if not memory['passed'] or memory['trace_sha256']!=hashlib.sha256(scene_path.read_bytes()).hexdigest():raise ValueError('Memory evidence does not pass on the scene trace')
    for filename,digest in memory['models'].items():
        if hashlib.sha256((ROOT/'treehouse-demo'/filename).read_bytes()).hexdigest()!=digest:raise ValueError('Memory evidence uses an older model')
    if scene['events']!=cache['events'] or scene['boundaries']!=cache['boundaries'] or scene['actions']!=cache['actions']:raise ValueError('Separate observers do not describe the same native execution')
    if cache['work']['routine']!='resident:7A66':raise ValueError('Missing cache profile')
    initial=(scene_path.parent/scene['heap'][0]['path']).read_bytes();shapes,_=shape_calls(scene,initial)
    if len(shapes)!=79 or len(memory['shapeChecks'])!=79 or len(memory['checks'])!=104:raise ValueError('Incomplete generated memory coverage')
    pairs=list(zip(shapes,memory['shapeChecks']))
    if memory.get('soundChecks'):
        sounds,_=sound_calls(scene,initial)
        if len(sounds)!=2399 or len(memory['soundChecks'])!=2399:raise ValueError('Incomplete generated sound coverage')
        pairs.extend(zip(sounds,memory['soundChecks']))
    base=cache['location']['main_base']+0xd510;counts={c['ordinal']:{} for c in cache['work']['calls']}
    for c in cache['work']['counts']:counts[c['call']][str(c['address']-base)]=c['entries']
    results=[]
    for shape,generated in pairs:
        if shape['key']!=generated['key'] or not generated['passed']:raise ValueError('Generated source correspondence differs')
        calls=[c for c in cache['work']['calls'] if shape['milliseconds']<=c['begin'] and c['end']<=shape['end']]
        if len(calls)!=1:raise ValueError('Source load does not contain exactly one cache call')
        native=calls[0];model=generated['sourceWork'];input=model['input'];actual=counts[native['ordinal']]
        input_equal=[input['cachedHandle'],input['state'],input['segment']]==native['header']
        differences={a:dict(expected=model['entries'].get(a,0),actual=actual.get(a,0)) for a in actual.keys()|model['entries'].keys() if actual.get(a,0)!=model['entries'].get(a,0)}
        results.append(dict(key=shape['key'],action=model['action'],instructions=model['instructions'],input_equal=input_equal,differences=differences,passed=input_equal and not differences))
    report=dict(passed=all(r['passed'] for r in results),checks=results,matching_calls=sum(r['passed'] for r in results),models=memory['models'],
        memory_report_sha256=hashlib.sha256(memory_path.read_bytes()).hexdigest(),scene_trace_sha256=hashlib.sha256(scene_path.read_bytes()).hexdigest(),cache_trace_sha256=hashlib.sha256(cache_path.read_bytes()).hexdigest(),
        scope=f"All {len(pairs)} shape/sound source cache states and intrinsic instruction paths are generated by the continuous memory model, then compared with native observations. No per-call cache state is supplied to that model. The model starts from one explicit initial RAM/catalog fixture and uses observed surrounding memory requests outside the generated loaders. Startup, remaining resource callers and full timing integration remain open.")
    (output/'report.json').write_text(json.dumps(report,indent=2),encoding='utf-8');print(json.dumps({**report,'checks':[r for r in results if not r['passed']]},indent=2));return report['passed']


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--memory',type=Path,required=True);p.add_argument('--scene',type=Path,required=True);p.add_argument('--cache',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args();sys.exit(0 if verify(a.memory,a.scene,a.cache,a.output) else 1)
