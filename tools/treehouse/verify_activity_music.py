"""Bounded native MIDI-prefix and Godot activity music import/control proof.

The native route enters the maze normally, runs its tutorial, returns to the
piano, and interrupts reentry. Tracks are identified by unique source-event
prefixes, without seeking, rewriting the guest, or adjusting timer ordinals.
This does not prove full FM waveform or wall-clock equivalence.
"""
import argparse
import hashlib
import json
from pathlib import Path
import wave

from build_demo import ROOT
from midi import extract


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify(native, control, godot, output):
    output.mkdir(parents=True, exist_ok=False)
    checks = []
    def check(name, passed, **detail):
        checks.append(dict(name=name, passed=bool(passed), **detail))
    run = json.loads((native / 'run.json').read_text(encoding='utf-8'))
    other = json.loads((control / 'run.json').read_text(encoding='utf-8'))
    check('paired original run identity', run['passed'] and other['passed'] and all(
        run[k] == other[k] for k in ('actions', 'checkpoints', 'core_sha256', 'content_sha256', 'restore_sha256')))
    for name in ('frames.jsonl', 'state/audio.wav', 'state/final-piano.ram-0'):
        check('observer preserves ' + name, sha(native / name) == sha(control / name))
    music = extract(ROOT / 'testing/output/treehouse/source/The_Treehouse_1991.zip')
    expected = {key:[{k:e[k] for k in ('irq','status','data')} for e in track['native']['events'] if e['kind']=='channel']
                for key, track in music['tracks'].items()}
    events = run['midi_events']
    resets = [i for i,e in enumerate(events) if e['label']=='fm.dispatch' and e['ax'] & 255 == 4]
    seen = set()
    spans = []
    for begin, end in zip(resets, resets[1:] + [len(events)]):
        irq, channel = 0, []
        for event in events[begin:end]:
            if event['label']=='midi.irq':
                irq += 1
            elif event['label']=='midi.event' and event['ax'] & 255 < 0xf0:
                status = (event['ax'] & 255) | (event['ax'] >> 8)
                data = [event['dx'] & 255]
                if status >> 4 not in (12,13):
                    data.append(event['dx'] >> 8)
                channel.append(dict(irq=irq, status=status, data=data))
        if not channel:
            continue
        matches = [key for key, values in expected.items() if channel == values[:len(channel)]]
        check(f'native accompaniment {len(spans)} has exact unique source prefix', len(matches)==1,
              matches=matches, events=len(channel), duration_irqs=irq)
        seen.update(matches)
        spans.append(dict(begin_event=begin, end_event=end, tracks=matches, channel_events=channel, duration_irqs=irq))
    check('all four frog variants observed through ordinary input', seen=={f'midisnd:{i}' for i in range(20100,20104)})
    component = json.loads(godot.read_text(encoding='utf-8'))
    checks.extend(component['checks'])
    for sound in (20001,20100,20101,20102,20103):
        path = ROOT / f'treehouse-godot/data/music-{sound}.wav'
        with wave.open(str(path)) as stream:
            check(f'imported PCM {sound} retains every source-generated byte',
                  hashlib.sha256(stream.readframes(stream.getnframes())).hexdigest()==component['pcm_sha256'][str(sound)])
    report = dict(passed=all(c['passed'] for c in checks), checks=checks, native_spans=spans,
                  files={str(p):sha(p) for p in (native/'run.json',control/'run.json',godot)},
                  limits=['Native observations cover interrupted prefixes of all four frog tracks, not complete loops.',
                          'Home trigger and EOT controls are source-derived component checks; native Home audio remains unverified.',
                          'PCM synthesis starts with a reset chip; retained oscillator/envelope state and original mixer/wall-clock timing remain open.'])
    (output/'report.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(dict(passed=report['passed'],checks=len(checks),failures=[c for c in checks if not c['passed']])))
    return report['passed']


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ('native','control','godot','output'):
        parser.add_argument('--'+name,type=Path,required=True)
    args=parser.parse_args()
    raise SystemExit(0 if verify(args.native,args.control,args.godot,args.output) else 1)
